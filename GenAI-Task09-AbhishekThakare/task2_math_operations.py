# This program demonstrates mathematical operations using NumPy

import numpy as np

A = np.array([10, 20, 30, 40])
B = np.array([1, 2, 3, 4])

print("Addition:")
print(A + B)

print("\nSubtraction:")
print(A - B)

print("\nMultiplication:")
print(A * B)

print("\nDivision:")
print(A / B)

print("\nPower:")
print(A ** 2)
