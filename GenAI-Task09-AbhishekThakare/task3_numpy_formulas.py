# This program demonstrates important NumPy mathematical formulas

import numpy as np

values = np.array([2, 4, 6, 8, 10])

print("Square Root:")
print(np.sqrt(values))

print("\nExponential:")
print(np.exp(values))

print("\nNatural Logarithm:")
print(np.log(values))

print("\nSum of Elements:")
print(np.sum(values))

print("\nCumulative Sum:")
print(np.cumsum(values))
